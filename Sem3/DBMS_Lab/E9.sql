SELECT e1.*
FROM EMP e1
JOIN EMP e2
    ON e2.ENAME = 'BLAKE'
WHERE e1.SAL > e2.SAL;


-- Q2
SELECT e1.*
FROM EMP e1
JOIN EMP e2
    ON e2.ENAME = 'ALLEN'
WHERE e1.JOB = e2.JOB;


-- Q3
SELECT e1.*
FROM EMP e1
JOIN EMP e2
    ON e1.SAL = e2.SAL
WHERE e2.ENAME IN ('FORD', 'SMITH')
ORDER BY e1.ENAME DESC;


-- Q4
SELECT e1.*
FROM EMP e1
LEFT JOIN EMP e2
    ON e2.ENAME = 'MILLER'
LEFT JOIN EMP e3
    ON e3.ENAME = 'ALLEN'
WHERE e1.JOB = e2.JOB
   OR e1.SAL > e3.SAL;


-- Q5
SELECT e.*
FROM EMP e
JOIN DEPT d
    ON e.DEPTNO = d.DEPTNO
JOIN (
    SELECT DEPTNO, MAX(SAL) AS MAX_SAL
    FROM EMP
    GROUP BY DEPTNO
) m
    ON e.DEPTNO = m.DEPTNO
   AND e.SAL = m.MAX_SAL
WHERE d.DNAME = 'SALES';


-- Q6
SELECT e1.*
FROM EMP e1
JOIN (
    SELECT MAX(e2.HIREDATE) AS MAX_HIREDATE
    FROM EMP e2
    JOIN EMP king
        ON e2.MGR = king.EMPNO
    WHERE king.ENAME = 'KING'
) x
    ON e1.HIREDATE < x.MAX_HIREDATE;


-- Q7
SELECT e.ENAME
FROM EMP e
JOIN (
    SELECT DEPTNO, MAX(SAL) AS MAX_SAL
    FROM EMP
    GROUP BY DEPTNO
) m
    ON e.DEPTNO = m.DEPTNO
   AND e.SAL = m.MAX_SAL;


-- Q8
SELECT e.*
FROM EMP e
JOIN (
    SELECT (MAX(SAL) + MIN(SAL)) / 2 AS AVG_EXTREME_SAL
    FROM EMP
) x
    ON e.SAL = x.AVG_EXTREME_SAL;


-- Q9
SELECT e1.*
FROM EMP e1
JOIN EMP e2
    ON e1.HIREDATE = e2.HIREDATE
   AND e1.EMPNO <> e2.EMPNO;


-- Q10
SELECT e1.*
