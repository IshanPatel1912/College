-- Q1
SELECT d.DEPTNO
FROM DEPT d
LEFT JOIN EMP e
    ON d.DEPTNO = e.DEPTNO
WHERE e.EMPNO IS NULL;


-- Q2
SELECT
    DEPTNO,
    JOB,
    COUNT(EMPNO) AS NO_OF_EMPS,
    AVG(SAL) AS AVG_SALARY
FROM EMP
GROUP BY DEPTNO, JOB
ORDER BY DEPTNO, JOB;


-- Q3
SELECT MAX(AVG_SALARY) AS MAX_AVG_SALARY
FROM (
    SELECT JOB, AVG(SAL) AS AVG_SALARY
    FROM EMP
    WHERE JOB <> 'President'
    GROUP BY JOB
) JobAverages;


-- Q4
SELECT
    d.DEPTNO,
    d.DNAME,
    d.LOC
FROM DEPT d
JOIN EMP e
    ON d.DEPTNO = e.DEPTNO
GROUP BY d.DEPTNO, d.DNAME, d.LOC
HAVING COUNT(e.EMPNO) >= 2;


-- Q5
SELECT
    DEPTNO,
    COUNT(EMPNO) AS NO_OF_EMPS
FROM EMP
GROUP BY DEPTNO
HAVING COUNT(EMPNO) > 3;


-- Q6
SELECT
    e.DEPTNO,
    e.ENAME,
    e.SAL
FROM EMP e
JOIN (
    SELECT DEPTNO, MAX(SAL) AS MAX_SAL
    FROM EMP
    GROUP BY DEPTNO
) m
    ON e.DEPTNO = m.DEPTNO
   AND e.SAL = m.MAX_SAL
ORDER BY e.DEPTNO;


-- Q7
SELECT
    d.DEPTNO,
    d.DEPT_AVG_SALARY
FROM (
    SELECT DEPTNO, AVG(SAL) AS DEPT_AVG_SALARY
    FROM EMP
    GROUP BY DEPTNO
) d
JOIN (
    SELECT AVG(SAL) AS COMPANY_AVG_SALARY
    FROM EMP
) c
    ON d.DEPT_AVG_SALARY < c.COMPANY_AVG_SALARY
ORDER BY d.DEPT_AVG_SALARY DESC;