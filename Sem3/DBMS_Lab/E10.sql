DELIMITER //
CREATE TRIGGER CHECK_SALARY_INSERT
BEFORE INSERT ON EMPLOYEE
FOR EACH ROW
BEGIN
    IF NEW.SALARY < 20000 THEN
        SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = 'Salary must not be less than 20000.';
    END IF;
END //

CREATE TRIGGER CHECK_SALARY_UPDATE
BEFORE UPDATE ON EMPLOYEE
FOR EACH ROW
BEGIN
    IF NEW.SALARY < 20000 THEN
        SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = 'Salary must not be less than 20000.';
    END IF;
END //
DELIMITER ;

