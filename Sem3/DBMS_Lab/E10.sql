--Q.9
DELIMITER //
CREATE PROCEDURE INCREASE_SALARY(
    IN p_emp_id INT, 
    IN p_percentage DECIMAL(5,2)
)
BEGIN
    UPDATE EMPLOYEE
    SET SALARY = SALARY + (SALARY * (p_percentage / 100))
    WHERE EMP_ID = p_emp_id;
END //
DELIMITER ;

