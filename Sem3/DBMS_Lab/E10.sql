CREATE MATERIALIZED VIEW DEPT_SALARY_SUMMARY
BUILD IMMEDIATE
REFRESH COMPLETE ON DEMAND
AS
SELECT 
    DEPT_ID, 
    SUM(SALARY) AS TOTAL_SALARY, 
    AVG(SALARY) AS AVG_SALARY
FROM EMPLOYEE
GROUP BY DEPT_ID;

