--Q.1
SELECT DEPTNO
FROM DEPT
WHERE DEPTNO NOT IN (
    SELECT DEPTNO
    FROM EMP
);

--Q.2
SELECT 
    DEPTNO,
    JOB,
    COUNT(EMPNO) AS NO_OF_EMPS,
    AVG(SAL) AS AVG_SALARY
FROM 
    EMP
GROUP BY 
    DEPTNO, 
    JOB
ORDER BY 
    DEPTNO, 
    JOB;

--Q3.
SELECT MAX(AVG_SALARY) AS MAX_AVG_SALARY
FROM (
    SELECT JOB, AVG(SAL) AS AVG_SALARY
    FROM EMP
    WHERE JOB <> 'President'
    GROUP BY JOB
) AS JobAverages;

--Q4.
SELECT DEPTNO, DNAME, LOC
FROM DEPT
WHERE DEPTNO IN (
    SELECT DEPTNO
    FROM EMP
    GROUP BY DEPTNO
    HAVING COUNT(EMPNO) >= 2
);

--Q5.
SELECT 
    DEPTNO, 
    COUNT(EMPNO) AS NO_OF_EMPS
FROM 
    EMP
GROUP BY 
    DEPTNO
HAVING 
    COUNT(EMPNO) > 3;

--Q6.
SELECT 
    e.DEPTNO, 
    e.ENAME, 
    e.SAL
FROM 
    EMP e
WHERE 
    e.SAL = (
        SELECT MAX(SAL) 
        FROM EMP 
        WHERE DEPTNO = e.DEPTNO
    )
ORDER BY 
    e.DEPTNO;

--Q7.
SELECT 
    DEPTNO, 
    AVG(SAL) AS DEPT_AVG_SALARY
FROM 
    EMP
GROUP BY 
    DEPTNO
HAVING 
    AVG(SAL) < (SELECT AVG(SAL) FROM EMP)
ORDER BY 
    DEPT_AVG_SALARY DESC;
